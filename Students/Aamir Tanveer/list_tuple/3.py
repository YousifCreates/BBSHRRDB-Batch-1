import random
marks_1 = [random.randrange(0, 100) for i in range(5)]
print("Marks of Student 1 in diff Subject",marks_1)

total_marks_1 = 0

for i in range(0, len(marks_1)):
    total_marks_1 += marks_1[i]

print("Total marks of student 1:", total_marks_1)
print(f"Average marks of student 1: {total_marks_1 / len(marks_1)}")
print("Max marks of student 1:", max(marks_1))
print("Min marks of student 1:", min(marks_1))





